export const maxDuration = 300

const PROJECT_ID = process.env.NEXT_PUBLIC_SANITY_PROJECT_ID ?? "4rllejq1"
const DATASET    = process.env.NEXT_PUBLIC_SANITY_DATASET    ?? "production"
const BASE_URL   = `https://${PROJECT_ID}.api.sanity.io/v2023-05-03/data/query/${DATASET}`

async function sanityFetch(query: string) {
  const res = await fetch(`${BASE_URL}?query=${encodeURIComponent(query)}`, { cache: "no-store" })
  if (!res.ok) throw new Error(`Sanity fetch failed: ${res.status}`)
  const data = await res.json()
  return data.result
}

async function buildCourse(slug: string) {
  const course = await sanityFetch(`
    *[_type == "course" && slug.current == "${slug}" && (status == "published" || !defined(status))][0] {
      _id, title, slug, description, level,
      "categoryTitle": category->title,
      "chapters": chapters[] {
        _key, chapterTitle, chapterOrder,
        "lessons": lessons[defined(@->._id) && !(@->_id in path("drafts.**"))]-> {
          _id, title, slug, order,
          "linkedArticles": linkedArticles[defined(@->._id) && !(@->_id in path("drafts.**"))]-> {
            _id, title, slug, excerpt, mcqUrl, body
          }
        }
      }
    }
  `)
  if (!course) throw new Error("Course not found")

  const chapters = await Promise.all(
    (course.chapters || []).map(async (chapter: any) => {
      const lessons = await Promise.all(
        (chapter.lessons || []).map(async (lesson: any) => {
          const linkedArticles = await Promise.all(
            (lesson.linkedArticles || []).map(async (article: any) => {
              let quizQuestions: any[] = []
              if (article.mcqUrl) {
                const parts = article.mcqUrl.split("/")
                const practiceSlug = parts[parts.length - 1]
                try {
                  const practicePost = await sanityFetch(`
                    *[_type == "practicePost" && slug.current == "${practiceSlug}" && "accountingbody" in showOnSites][0] {
                      "quizQuestions": quizQuestions[] {
                        questionText, options, correctIndex, explanation, difficulty, timeTargetMinutes
                      }
                    }
                  `)
                  quizQuestions = practicePost?.quizQuestions || []
                } catch {
                  quizQuestions = []
                }
              }
              return { ...article, quizQuestions }
            })
          )
          return { ...lesson, linkedArticles }
        })
      )
      return { ...chapter, lessons }
    })
  )
  return { ...course, chapters }
}

const BOOK_TYPE_LABELS: Record<string, string> = {
  combined: "Study Text and Practice Kit",
  study:    "Study Text",
  practice: "Practice Kit",
}

function buildMetadata(subtitle: string, bookType: string, edition: string, course: any): string {
  const lines = [
    "ACCOUNTING BODY PRESS - BOOK METADATA",
    "=====================================",
    "",
    `Title: ${subtitle}`,
    `Type: ${BOOK_TYPE_LABELS[bookType] || bookType}`,
    `Author: Accounting Body Editorial Team`,
    `Publisher: Accounting Body Press`,
    `Edition: ${edition}`,
    `Year: ${new Date().getFullYear()}`,
    `Language: English`,
    `Trim Size: 6 x 9 inches`,
    `Interior: Black and White`,
    `Paper: White`,
    "",
    "COURSE INFO",
    "-----------",
    `Course: ${course.title}`,
    `Level: ${course.level || "Not specified"}`,
    `Category: ${course.categoryTitle || "Not specified"}`,
    `Chapters: ${(course.chapters || []).length}`,
    "",
    "KDP UPLOAD INSTRUCTIONS",
    "-----------------------",
    "1. Log in to kdp.amazon.com",
    "2. Create new paperback title",
    "3. Enter metadata from above",
    "4. Upload interior.pdf as manuscript",
    "5. Upload cover.pdf as cover",
    "6. Choose 6x9 trim size, black and white interior",
    "7. Set price and territories",
    "8. Submit for review",
    "",
    `Generated: ${new Date().toISOString()}`,
    "Generated by: Accounting Body Press Publishing System",
  ]
  return lines.join("\n")
}

// ── ZIP builder (no external dependency) ─────────────────────────────────────
function u32le(n: number): Buffer {
  const b = Buffer.alloc(4); b.writeUInt32LE(n, 0); return b
}
function u16le(n: number): Buffer {
  const b = Buffer.alloc(2); b.writeUInt16LE(n, 0); return b
}
function crc32(buf: Buffer): number {
  const t: number[] = []
  for (let i = 0; i < 256; i++) {
    let c = i
    for (let j = 0; j < 8; j++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    t[i] = c
  }
  let crc = 0xffffffff
  for (let i = 0; i < buf.length; i++) crc = t[(crc ^ buf[i]) & 0xff] ^ (crc >>> 8)
  return (crc ^ 0xffffffff) >>> 0
}
function buildZip(files: { name: string; data: Buffer }[]): Buffer {
  const locals: Buffer[] = []
  const centrals: Buffer[] = []
  let offset = 0
  for (const f of files) {
    const name = Buffer.from(f.name, "utf8")
    const crc  = crc32(f.data)
    const size = f.data.length
    const local = Buffer.concat([
      Buffer.from([0x50,0x4b,0x03,0x04]),
      u16le(20),u16le(0),u16le(0),u16le(0),u16le(0),
      u32le(crc),u32le(size),u32le(size),
      u16le(name.length),u16le(0),
      name, f.data,
    ])
    locals.push(local)
    centrals.push(Buffer.concat([
      Buffer.from([0x50,0x4b,0x01,0x02]),
      u16le(20),u16le(20),u16le(0),u16le(0),u16le(0),u16le(0),
      u32le(crc),u32le(size),u32le(size),
      u16le(name.length),u16le(0),u16le(0),u16le(0),u16le(0),
      u32le(0),u32le(offset),name,
    ]))
    offset += local.length
  }
  const cd   = Buffer.concat(centrals)
  const eocd = Buffer.concat([
    Buffer.from([0x50,0x4b,0x05,0x06]),
    u16le(0),u16le(0),
    u16le(files.length),u16le(files.length),
    u32le(cd.length),u32le(offset),u16le(0),
  ])
  return Buffer.concat([...locals, cd, eocd])
}

// ── POST handler ─────────────────────────────────────────────────────────────
export async function POST(req: NextRequest) {
  try {
    const body = await req.json()
    const { slug, bookType, edition, subtitle } = body
    if (!slug)     return NextResponse.json({ error: "slug is required" },     { status: 400 })
    if (!bookType) return NextResponse.json({ error: "bookType is required" }, { status: 400 })

    const course = await buildCourse(slug)

    const interiorPdf = await renderToBuffer(
      React.createElement(BookTemplate, {
        course,
        bookType: bookType as any,
        edition:  edition  || "2026/27 Edition",
        subtitle: subtitle || course.title,
      }) as any
    )

    // Count pages from interior PDF for dynamic spine width
    const interiorStr = interiorPdf.toString("binary")
    const pageMatches = interiorStr.match(/\/Type\s*\/Page[^s]/g)
    const pageCount = pageMatches ? pageMatches.length : 300

    // Render full wrap cover (front + spine + back) with dynamic spine
    const coverPdf = await renderToBuffer(
      React.createElement(FullCoverTemplate, {
        subtitle:  subtitle || course.title,
        bookType:  bookType as any,
        edition:   edition  || "2026/27 Edition",
        pageCount,
      }) as any
    )

    const metaBuffer = Buffer.from(
      buildMetadata(subtitle || course.title, bookType, edition || "2026/27 Edition", course),
      "utf8"
    )

    const zip      = buildZip([
      { name: "interior.pdf", data: interiorPdf },
      { name: "cover.pdf",    data: coverPdf    },
      { name: "metadata.txt", data: metaBuffer  },
    ])
    const filename = `${slug}-${bookType}.zip`

    return new NextResponse(new Uint8Array(zip), {
      status: 200,
      headers: {
        "Content-Type":        "application/zip",
        "Content-Disposition": `attachment; filename="${filename}"`,
        "Content-Length":      String(zip.length),
      },
    })
  } catch (err: unknown) {
    const msg = err instanceof Error ? err.message : "Unknown error"
    return NextResponse.json({ error: msg }, { status: 500 })
  }
}

/**
 * article-normaliser.ts
 *
 * Converts any AI-generated or exported article JSON (ChatGPT, DeepSeek,
 * Gemini, Claude, hand-written, WordPress export, etc.) into the exact
 * shape the Supabase `articles` table expects.
 *
 * Same architecture as lib/question-normaliser.ts (S37): a normaliser that
 * is lenient about input shape and field naming, logs every transformation
 * it makes so the admin UI can render a diff report, and defers hard
 * publish-readiness checks to a separate `validateNormalisedArticle` pass.
 *
 * Zero runtime dependencies beyond the standard library — safe to import
 * from Node.js API routes or an edge runtime.
 */

// ── Public types ─────────────────────────────────────────────────────────────

/**
 * Every `articles` table column except the ones never set by the normaliser:
 * id (generated by Supabase), content_id (assigned at publish time),
 * created_at / updated_at (set by the database).
 */
export interface NormalisedArticle {
  title:               string
  slug:                string
  content:             string
  excerpt:             string
  category:            string
  category_title:      string
  exam_body:           string[]
  show_on_sites:        string[]
  featured_image_url:  string
  seo_title:           string
  seo_description:     string
  mcq_url:             string
  read_time:           number
  author_name:         string
  last_reviewed:       string | null
  status:              string
  platform:            string
  canonical_owner:     string
  wp_id:               string
  ai_summary:          string
  ai_key_terms:        string[]
  ai_searchable:       boolean
  eticpa_level:        string
  eticpa_module:       string
  eticpa_topic:        string
  content_type:        string
  difficulty:          string
  published_at:        string | null
}

export interface NormaliseArticleResult {
  article:  NormalisedArticle
  changes:  string[]
  warnings: string[]
}

export interface NormaliseManyArticlesResult {
  articles: NormalisedArticle[]
  changes:  string[][]
  warnings: string[][]
}


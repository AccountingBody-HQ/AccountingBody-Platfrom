function buildCountryKeys(): Readonly<Record<string, string>> {
  // No prototype, so a segment such as "constructor" never matches an
  // inherited property.
  const keys: Record<string, string> = Object.create(null)
  for (const name of COUNTRY_CANONICAL_NAMES) {
    const key = name.toLowerCase()
    if (!EXCLUDED_COUNTRY_KEYS.has(key)) keys[key] = name
  }
  for (const [key, name] of Object.entries(COUNTRY_ALIASES)) {
    keys[key] = name
  }
  return Object.freeze(keys)
}

/** Lowercase lookup key → canonical country name. */
export const COUNTRY_KEYS: Readonly<Record<string, string>> = buildCountryKeys()
